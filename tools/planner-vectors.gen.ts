// Writes tools/planner-vectors.json from the phone's planner core. Run from node/:
//   node --import tsx ../tools/planner-vectors.gen.ts
// Both app/src/__tests__/sim.test.ts and node/test/planner.test.ts replay the file, so the
// two copies of the core (app/src/llm/sim/model.ts, node/src/sim.ts) are known to agree.
import { writeFileSync } from 'node:fs';
import { planShares, MB, type PlanInput, type SimModel } from '../app/src/llm/sim/model.ts';

type M = Omit<SimModel, 'fileMb'> & { fileBytes: number };
const models: Record<string, M> = {
  q06: { id: 'qwen3-0.6b-q8', fileBytes: 639446688, layers: 28, hidden: 1024, vocab: 151936, bytesPerParam: 1, kvMbPer1k: 56 },
  l3b: { id: 'llama3.2-3b-q4', fileBytes: 2019377696, layers: 28, hidden: 3072, vocab: 128256, bytesPerParam: 0.55, kvMbPer1k: 112 },
  q7: { id: 'qwen2.5-7b-q4', fileBytes: 4683074240, layers: 28, hidden: 3584, vocab: 152064, bytesPerParam: 0.55, kvMbPer1k: 56 },
};
const dev = (id: string, capMb: number, bw: number, eff = 0.6) => ({ id, capMb, bw, eff });
const wifi5 = { mbps: 30, rttMs: 3 }, wifi24 = { mbps: 5, rttMs: 8 }, nat = { mbps: 1.3, rttMs: 2 };
const cases: { name: string; input: Omit<PlanInput, 'model'> & { model: M } }[] = [
  { name: 'fits alone, no share', input: { model: models.q06, ctx: 2048, local: dev('me', 4550, 65.9), workers: [dev('a', 2850, 28)], net: wifi5, share: false } },
  { name: 'fits alone, share on wi-fi 5', input: { model: models.q06, ctx: 2048, local: dev('me', 4550, 65.9), workers: [dev('a', 2850, 28), dev('b', 1950, 14)], net: wifi5, share: true } },
  { name: 'emulator + mac over nat', input: { model: models.q06, ctx: 2048, local: dev('me', 770, 12), workers: [dev('mac', 3000, 68, 0.3)], net: nat, share: true } },
  { name: '7b on s25+ with three phones', input: { model: models.q7, ctx: 2048, local: dev('me', 4550, 65.9), workers: [dev('pixel', 2850, 28), dev('mid', 1950, 14), dev('old', 1050, 8)], net: wifi5, share: true } },
  { name: '7b at ctx 8192', input: { model: models.q7, ctx: 8192, local: dev('me', 4550, 65.9), workers: [dev('pixel', 2850, 28), dev('mid', 1950, 14), dev('old', 1050, 8)], net: wifi5, share: true } },
  { name: "3b, small master, four faster workers, fast net", input: { model: models.l3b, ctx: 2048, local: dev("me", 2500, 20), workers: ["a", "b", "c", "d"].map((id) => dev(id, 900, 30)), net: { mbps: 100, rttMs: 0.5 }, share: true } },
  { name: "3b, small master, four faster workers, 2.4 ghz", input: { model: models.l3b, ctx: 2048, local: dev("me", 2500, 20), workers: ["a", "b", "c", "d"].map((id) => dev(id, 900, 30)), net: wifi24, share: true } },
  { name: 'unknown peer defaults (2000 mb × 0.75, 4 GB/s)', input: { model: models.q06, ctx: 2048, local: dev('me', 1400, 4), workers: [dev('x', 1500, 4)], net: wifi5, share: true } },
  { name: 'too big together', input: { model: models.q7, ctx: 2048, local: dev('me', 980, 8), workers: [dev('a', 1050, 8)], net: wifi5, share: true } },
  { name: 'master too small for the output layer', input: { model: models.q7, ctx: 2048, local: dev('me', 200, 10), workers: [dev('gpu', 16500, 1008)], net: wifi5, share: true } },
];
const vectors = cases.map((c) => {
  const model = { ...c.input.model, fileMb: c.input.model.fileBytes / MB } as SimModel & { fileBytes?: number };
  delete model.fileBytes;
  try {
    const p = planShares({ ...c.input, model });
    return { name: c.name, input: c.input, expect: { localMb: p.localMb, used: p.used, needMb: p.needMb, aloneFaster: p.aloneFaster, est: p.est } };
  } catch (e) {
    return { name: c.name, input: c.input, error: (e as Error).message };
  }
});
writeFileSync(new URL('./planner-vectors.json', import.meta.url), JSON.stringify({ note: 'generated by tools/planner-vectors.gen.ts; do not edit by hand', vectors }, null, 1) + '\n');
console.log(`${vectors.length} vectors written`);
