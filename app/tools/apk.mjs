#!/usr/bin/env node
// npm run apk — a release apk that talks to kula's live server, in one command:
//   1. tools/release-env.mjs: refuse a build without a live server (stops here today,
//      until app/.env.production has kula's Supabase project)
//   2. expo prebuild --platform android --clean (android/ is generated, never edited)
//   3. android/local.properties (the SDK), resource validation off (react-native-screens)
//   4. gradlew assembleRelease with JDK 17 and the SDK
//   5. dist/kula-decentralized-ai-<version>.apk
// `npm run apk -- --fast` (5.11.2026): for the phone on the desk. Only arm64-v8a (every phone
// kula runs a model on; the llama module builds nothing else anyway), gradle's daemon kept,
// and android/ regenerated in place instead of from scratch, so the native builds already
// done (llama.cpp, react native's c++) are reused. After adding a native package or changing
// app.json plugins, run the full build once.
// Knobs for CI (.github/workflows/apk.yml), all optional:
//   KULA_GRADLE_ARGS      extra gradle arguments, e.g. "-PkulaLlamaVariants=min" (one cpu variant, fast)
//   KULA_KEYSTORE_FILE    + KULA_KEYSTORE_PASSWORD, KULA_KEY_ALIAS, KULA_KEY_PASSWORD: sign the release
//                         with this keystore instead of expo's debug key (a debug-signed apk installs,
//                         but no store takes it and a later real-signed build will not update over it)
// The recipe of 21.10.2026, when the same steps took a dozen tries by hand. After moving
// or renaming the repo folder, delete android/ and every node_modules/*/android/{build,.cxx}
// first: they keep absolute paths and break CMake in odd ways.
import { execFileSync } from "node:child_process";
import { appendFileSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const app = new URL("..", import.meta.url).pathname;
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { cwd: app, stdio: "inherit", ...opts });
const sdk = process.env.ANDROID_HOME ?? join(homedir(), "Library/Android/sdk");
const jdk = process.env.JAVA_HOME ?? join(homedir(), "Library/Java/JavaVirtualMachines/jdk-17.0.20.1+1/Contents/Home");
for (const [what, path] of [["Android SDK", sdk], ["JDK 17", jdk]]) {
  if (!existsSync(path)) { console.error(`✗ ${what} not found at ${path} (set ${what === "JDK 17" ? "JAVA_HOME" : "ANDROID_HOME"})`); process.exit(1); }
}

const fast = process.argv.includes("--fast");
run("node", ["tools/release-env.mjs"]);
run("npx", ["expo", "prebuild", "--platform", "android", ...(fast && existsSync(join(app, "android")) ? [] : ["--clean"]), "--no-install"]);
writeFileSync(join(app, "android/local.properties"), `sdk.dir=${sdk}\n`);
const props = join(app, "android/gradle.properties");
if (!readFileSync(props, "utf8").includes("android.disableResourceValidation")) appendFileSync(props, "\nandroid.disableResourceValidation=true\n");
// the release key (11.11.2026): with nothing in the environment, the key the person made on this
// Mac signs, its password read from the macOS Keychain (never printed, never written to a file)
const ownKey = join(homedir(), ".kula-signing", "kula-release.p12");
if (!process.env.KULA_KEYSTORE_FILE && process.platform === "darwin" && existsSync(ownKey)) {
  try {
    const pw = execFileSync("security", ["find-generic-password", "-s", "kula-release-keystore", "-a", "kula", "-w"], { encoding: "utf8" }).trim();
    Object.assign(process.env, { KULA_KEYSTORE_FILE: ownKey, KULA_KEYSTORE_PASSWORD: pw, KULA_KEY_ALIAS: "kula", KULA_KEY_PASSWORD: pw });
  } catch { console.log("release signing: the key in ~/.kula-signing has no password in the Keychain (kula-release-keystore)"); }
}
const keystore = process.env.KULA_KEYSTORE_FILE;
if (keystore && readFileSync(join(app, "android/app/build.gradle"), "utf8").includes("kula: release signing")) {
  console.log(`release signing: keystore ${keystore} (already in android/app/build.gradle)`);
} else if (keystore) {
  if (!existsSync(keystore)) { console.error(`✗ keystore not found at ${keystore} (KULA_KEYSTORE_FILE)`); process.exit(1); }
  // android/ is generated by prebuild just above, so this is a build-time addition, not a hand edit:
  // a second android {} block that points the release build type at the keystore from the environment.
  appendFileSync(join(app, "android/app/build.gradle"), `
// kula: release signing from the environment (tools/apk.mjs)
android {
  signingConfigs {
    kula {
      storeFile file(System.getenv("KULA_KEYSTORE_FILE"))
      storePassword System.getenv("KULA_KEYSTORE_PASSWORD")
      keyAlias System.getenv("KULA_KEY_ALIAS")
      keyPassword System.getenv("KULA_KEY_PASSWORD")
    }
  }
  buildTypes { release { signingConfig signingConfigs.kula } }
}
`);
  console.log(`release signing: keystore ${keystore}, alias ${process.env.KULA_KEY_ALIAS ?? "(unset)"}`);
} else {
  console.log("release signing: expo's debug key (set KULA_KEYSTORE_FILE to sign for real)");
}
const extra = (process.env.KULA_GRADLE_ARGS ?? "").split(/\s+/).filter(Boolean);
const speed = fast ? ["-PreactNativeArchitectures=arm64-v8a"] : ["--no-daemon"];
// Leave the computer usable while it builds (5.11.2026: the Mac froze during a build): gradle
// at low priority (nice 15, the compilers it starts inherit it) and at most 4 tasks at once.
// KULA_BUILD_NICE=0 builds at full speed.
const gentle = process.env.KULA_BUILD_NICE !== "0";
const workers = gentle ? ["--max-workers=4"] : [];
run(gentle ? "nice" : "./gradlew", [...(gentle ? ["-n", "15", "./gradlew"] : []), "assembleRelease", ...workers, ...speed, ...extra], { cwd: join(app, "android"), env: { ...process.env, JAVA_HOME: jdk, ANDROID_HOME: sdk, ANDROID_SDK_ROOT: sdk, NODE_ENV: "production" } });

const version = JSON.parse(readFileSync(join(app, "app.json"), "utf8")).expo.version;
mkdirSync(join(app, "../dist"), { recursive: true });
const out = join(app, `../dist/kula-decentralized-ai-${version}.apk`);
copyFileSync(join(app, "android/app/build/outputs/apk/release/app-release.apk"), out);
console.log(`✓ ${out}`);
