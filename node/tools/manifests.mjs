#!/usr/bin/env node
// Renders the package manager drafts from node/package.json and, when there
// is one, a SHA256SUMS of the packed binaries:
//
//   packaging/homebrew/kula-node.rb        brew formula (mac arm64/x64, linux x64/arm64)
//   packaging/winget/*.yaml                winget manifest set (win-x64)
//   packaging/nfpm.yaml                    nfpm config for .deb/.rpm (tools/deb.mjs makes the .deb by hand)
//
//   node tools/manifests.mjs [--sums dist/pack/SHA256SUMS] [--out ../packaging]
//
// Without --sums every hash is "0000…", a draft that says where the files
// are and what the version is; the release workflow renders them again with
// the real sums and attaches them to the release.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const REPO = 'kurtkurtkurt-del/kula-decentralized-ai';
const ZERO = '0'.repeat(64);

function parseArgs(argv) {
  const o = { sums: null, out: path.join(root, '..', 'packaging'), version: pkg.version };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--sums') o.sums = path.resolve(argv[++i]);
    else if (argv[i] === '--out') o.out = path.resolve(argv[++i]);
    else if (argv[i] === '--version') o.version = argv[++i];
    else throw new Error(`unknown argument ${argv[i]}`);
  }
  return o;
}

export function readSums(file) {
  const m = new Map();
  if (!file || !fs.existsSync(file)) return m;
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const [sum, name] = line.trim().split(/\s+\*?/);
    if (sum && name) m.set(name, sum);
  }
  return m;
}

export function render(version, sums) {
  const url = (t) => `https://github.com/${REPO}/releases/download/v${version}/kula-node-${version}-${t}`;
  const sha = (t) => sums.get(`kula-node-${version}-${t}`) ?? ZERO;
  const brew = `# kula-node ${version}: generated by node/tools/manifests.mjs, do not edit by hand.
# brew install --formula ./packaging/homebrew/kula-node.rb   (or from a tap that carries this file)
class KulaNode < Formula
  desc "Make this computer a worker in a kula phone cluster"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${url('mac-arm64')}"
      sha256 "${sha('mac-arm64')}"
    end
    on_intel do
      url "${url('mac-x64')}"
      sha256 "${sha('mac-x64')}"
    end
  end

  on_linux do
    on_arm do
      url "${url('linux-arm64')}"
      sha256 "${sha('linux-arm64')}"
    end
    on_intel do
      url "${url('linux-x64')}"
      sha256 "${sha('linux-x64')}"
    end
  end

  def install
    binary = Dir["kula-node-*"].first
    bin.install binary => "kula-node"
  end

  def caveats
    <<~EOS
      llama.cpp is fetched on first use (its sha256 is checked):
        kula-node setup
    EOS
  end

  test do
    assert_match "kula-node #{version}", shell_output("#{bin}/kula-node --version")
  end
end
`;
  const winVersion = `${version}.0`.split('.').slice(0, 4).join('.');
  const wingetId = 'KurtKurtKurt.KulaNode';
  const wingetHead = `# kula-node ${version}: generated by node/tools/manifests.mjs, do not edit by hand.
# yaml-language-server: $schema=https://aka.ms/winget-manifest.`;
  const wingetVersion = `${wingetHead}version.1.6.0.schema.json
PackageIdentifier: ${wingetId}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
`;
  const wingetLocale = `${wingetHead}defaultLocale.1.6.0.schema.json
PackageIdentifier: ${wingetId}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: kurtkurtkurt-del
PackageName: kula-node
PackageUrl: https://github.com/${REPO}
License: MIT
ShortDescription: Make this computer a worker in a kula phone cluster
ReleaseNotesUrl: https://github.com/${REPO}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: 1.6.0
`;
  const wingetInstaller = `${wingetHead}installer.1.6.0.schema.json
PackageIdentifier: ${wingetId}
PackageVersion: ${version}
InstallerType: portable
Commands:
  - kula-node
Installers:
  - Architecture: x64
    InstallerUrl: ${url('win-x64.exe')}
    InstallerSha256: ${sha('win-x64.exe').toUpperCase()}
    PortableCommandAlias: kula-node
ManifestType: installer
ManifestVersion: 1.6.0
`;
  const nfpm = `# kula-node ${version}: generated by node/tools/manifests.mjs, do not edit by hand.
# nfpm package --packager deb --target dist/pack/   (after node tools/pack.mjs --target linux-\${GOARCH})
# tools/deb.mjs makes the same .deb without nfpm.
name: kula-node
arch: \${GOARCH}
platform: linux
version: ${version}
section: utils
priority: optional
maintainer: kurtkurtkurt-del <noreply@github.com>
description: Make this computer a worker in a kula phone cluster.
vendor: kula
homepage: https://github.com/${REPO}
license: MIT
contents:
  - src: ./dist/pack/kula-node-${version}-linux-\${GOARCH}
    dst: /usr/bin/kula-node
    file_info:
      mode: 0755
`;
  return {
    'homebrew/kula-node.rb': brew,
    [`winget/${wingetId}.yaml`]: wingetVersion,
    [`winget/${wingetId}.locale.en-US.yaml`]: wingetLocale,
    [`winget/${wingetId}.installer.yaml`]: wingetInstaller,
    'nfpm.yaml': nfpm,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const o = parseArgs(process.argv.slice(2));
  const files = render(o.version, readSums(o.sums));
  for (const [rel, text] of Object.entries(files)) {
    const f = path.join(o.out, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text);
    console.error(`wrote ${path.relative(process.cwd(), f)}`);
  }
}
