// Writes node/src/ui/catalog.ts from the phone app's catalog (app/src/llm/catalog.ts): the
// chat page offers the same models with the same Hugging Face urls, sizes and sha256s, so a
// phone told to load one downloads exactly what its own models screen would. kula-node does
// not import app/ at run time (the packed binary has no app/ next to it); test/ui.test.ts
// fails while this copy is behind.
//
//   cd node && npx tsx tools/ui-catalog.ts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG } from '../../app/src/llm/catalog.ts';

export function uiRows() {
  return CATALOG.map((m) => ({
    id: m.id, name: m.name, family: m.family, params_b: m.params_b, ...(m.active_b ? { active_b: m.active_b } : {}), ...(m.read_share ? { read_share: m.read_share } : {}), quant: m.quant, repo: m.repo, file: m.file,
    size: m.size, sha256: m.sha256, license: m.license, ctx_max: m.ctx_max, kv_mb_per_1k: m.kv_mb_per_1k,
    blurb: m.blurb.en, good: m.good.en,
  }));
}

const here = path.dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(here, '..', 'src', 'ui', 'catalog.ts');
  const text = `// Generated by node/tools/ui-catalog.ts from app/src/llm/catalog.ts: do not edit by hand.
// The models the chat page offers; a phone fetches the file itself from \`url\`, sha256-checked.
export interface UiModel {
  id: string; name: string; family: string; params_b: number; active_b?: number; read_share?: number; quant: string; repo: string; file: string;
  size: number; sha256: string; license: string; ctx_max: number; kv_mb_per_1k: number; blurb: string; good: string;
}

export const UI_CATALOG: UiModel[] = ${JSON.stringify(uiRows(), null, 2)};

export const modelUrl = (m: Pick<UiModel, 'repo' | 'file'>): string => \`https://huggingface.co/\${m.repo}/resolve/main/\${m.file}\`;
`;
  fs.writeFileSync(out, text);
  console.log(`wrote ${out} (${CATALOG.length} models)`);
}
